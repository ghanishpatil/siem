"""SQLAlchemy ORM model for a normalized security event.

Timestamps are stored as naive datetimes that always represent UTC. The
application normalizes every incoming timestamp to UTC before persistence and
re-attaches UTC on the way out, so storage and retrieval are consistent.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Optional

from sqlalchemy import JSON, Boolean, DateTime, Index, Integer, String
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


def _utcnow_naive() -> datetime:
    """Current UTC time as a naive datetime (tzinfo stripped, value is UTC)."""
    return datetime.now(timezone.utc).replace(tzinfo=None)


class Event(Base):
    """A single normalized security event."""

    __tablename__ = "events"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    # Unique identifier from the source, or generated by the ingestion layer.
    event_uid: Mapped[str] = mapped_column(
        String(128), unique=True, index=True, nullable=False
    )

    # Event occurrence time, stored as naive UTC.
    timestamp: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)

    # Normalized category (see app.normalization.vocab).
    event_type: Mapped[str] = mapped_column(String(64), nullable=False, index=True)

    source_ip: Mapped[Optional[str]] = mapped_column(String(45), nullable=True, index=True)
    destination_ip: Mapped[Optional[str]] = mapped_column(String(45), nullable=True)
    destination_port: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    username: Mapped[Optional[str]] = mapped_column(String(255), nullable=True, index=True)
    host: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # Log-source / source-system identifier.
    source: Mapped[str] = mapped_column(String(128), nullable=False, default="unknown")

    # Normalized severity (see app.normalization.vocab).
    severity: Mapped[str] = mapped_column(String(16), nullable=False, index=True)

    # Distinguishes synthetic demo data from real collected telemetry.
    is_synthetic: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    # Original event payload, retained verbatim for investigation.
    raw_event: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False)

    # Ingestion time, stored as naive UTC.
    created_at: Mapped[datetime] = mapped_column(
        DateTime, nullable=False, default=_utcnow_naive
    )

    __table_args__ = (
        # Supports the default deterministic ordering (newest first).
        Index("ix_events_timestamp_id", "timestamp", "id"),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Event id={self.id} uid={self.event_uid!r} type={self.event_type!r}>"
